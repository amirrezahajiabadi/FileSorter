//! Junk Cleaner — safe scan and cleanup of caches, temporary files, and crash dumps.

use std::fs;
use std::path::{Path, PathBuf};
use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct JunkLocation {
    pub id: String,
    pub name: String,
    pub description: String,
    pub paths: Vec<String>,
    pub file_count: u64,
    pub total_bytes: u64,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CleanReport {
    pub files_deleted: u64,
    pub bytes_freed: u64,
    pub files_failed: u64,
    pub skipped_locked: Vec<String>,
}

fn local_appdata() -> Option<PathBuf> {
    std::env::var("LOCALAPPDATA").ok().map(PathBuf::from)
}

fn temp_dir() -> Option<PathBuf> {
    std::env::var("TEMP").ok().map(PathBuf::from).or_else(|| {
        std::env::var("TMP").ok().map(PathBuf::from)
    })
}

pub fn get_defined_locations() -> Vec<(String, String, String, Vec<PathBuf>)> {
    let mut locs = Vec::new();

    // 1. User Temp
    if let Some(t) = temp_dir() {
        if t.is_dir() {
            locs.push((
                "user_temp".to_string(),
                "User Temporary Files".to_string(),
                "Temporary files created by apps in %TEMP%".to_string(),
                vec![t],
            ));
        }
    }

    // 2. Crash Dumps
    if let Some(la) = local_appdata() {
        let dumps = la.join("CrashDumps");
        if dumps.is_dir() {
            locs.push((
                "crash_dumps".to_string(),
                "Application Crash Dumps".to_string(),
                "Crash dump logs generated by stopped applications".to_string(),
                vec![dumps],
            ));
        }

        // 3. Chrome Cache
        let chrome_cache = la.join("Google").join("Chrome").join("User Data").join("Default").join("Cache");
        if chrome_cache.is_dir() {
            locs.push((
                "chrome_cache".to_string(),
                "Google Chrome Cache".to_string(),
                "Temporary web data and media cache for Chrome".to_string(),
                vec![chrome_cache],
            ));
        }

        // 4. Edge Cache
        let edge_cache = la.join("Microsoft").join("Edge").join("User Data").join("Default").join("Cache");
        if edge_cache.is_dir() {
            locs.push((
                "edge_cache".to_string(),
                "Microsoft Edge Cache".to_string(),
                "Temporary web assets and browsing cache for Edge".to_string(),
                vec![edge_cache],
            ));
        }

        // 5. Firefox Cache
        let ff_profiles = la.join("Mozilla").join("Firefox").join("Profiles");
        if ff_profiles.is_dir() {
            let mut ff_caches = Vec::new();
            if let Ok(entries) = fs::read_dir(&ff_profiles) {
                for entry in entries.flatten() {
                    let cache2 = entry.path().join("cache2");
                    if cache2.is_dir() {
                        ff_caches.push(cache2);
                    }
                }
            }
            if !ff_caches.is_empty() {
                locs.push((
                    "firefox_cache".to_string(),
                    "Mozilla Firefox Cache".to_string(),
                    "Web assets cached across Firefox profiles".to_string(),
                    ff_caches,
                ));
            }
        }

        // 6. Thumbnails Cache
        let thumbs = la.join("Microsoft").join("Windows").join("Explorer");
        if thumbs.is_dir() {
            locs.push((
                "thumbnails".to_string(),
                "Windows Thumbnail Cache".to_string(),
                "Generated thumbnail cache files in Explorer".to_string(),
                vec![thumbs],
            ));
        }
    }

    // 7. Windows System Temp
    let win_root = std::env::var("SystemRoot").unwrap_or_else(|_| "C:\\Windows".into());
    let win_temp = PathBuf::from(win_root).join("Temp");
    if win_temp.is_dir() {
        locs.push((
            "win_temp".to_string(),
            "Windows System Temp".to_string(),
            "System-wide temporary directory (skips elevation-restricted files)".to_string(),
            vec![win_temp],
        ));
    }

    locs
}

fn walk_dir_stats(path: &Path, is_thumb: bool) -> (u64, u64) {
    let mut count = 0u64;
    let mut bytes = 0u64;

    let entries = match fs::read_dir(path) {
        Ok(e) => e,
        Err(_) => return (0, 0),
    };

    for entry in entries.flatten() {
        let p = entry.path();
        if p.is_dir() {
            let (c, b) = walk_dir_stats(&p, is_thumb);
            count += c;
            bytes += b;
        } else if p.is_file() {
            if is_thumb {
                let name = p.file_name().and_then(|n| n.to_str()).unwrap_or("");
                if !name.starts_with("thumbcache_") {
                    continue;
                }
            }
            if let Ok(meta) = entry.metadata() {
                count += 1;
                bytes += meta.len();
            }
        }
    }

    (count, bytes)
}

pub fn scan_junk_locations() -> Vec<JunkLocation> {
    let defs = get_defined_locations();
    let mut results = Vec::new();

    for (id, name, desc, paths) in defs {
        let is_thumb = id == "thumbnails";
        let mut file_count = 0u64;
        let mut total_bytes = 0u64;
        let path_strs: Vec<String> = paths.iter().map(|p| p.to_string_lossy().to_string()).collect();

        for p in &paths {
            let (c, b) = walk_dir_stats(p, is_thumb);
            file_count += c;
            total_bytes += b;
        }

        results.push(JunkLocation {
            id,
            name,
            description: desc,
            paths: path_strs,
            file_count,
            total_bytes,
        });
    }

    results
}

fn delete_recursive(path: &Path, is_thumb: bool, rep: &mut CleanReport) {
    let entries = match fs::read_dir(path) {
        Ok(e) => e,
        Err(_) => return,
    };

    for entry in entries.flatten() {
        let p = entry.path();
        if p.is_dir() {
            delete_recursive(&p, is_thumb, rep);
            // Try removing empty directory if not top-level
            let _ = fs::remove_dir(&p);
        } else if p.is_file() {
            if is_thumb {
                let name = p.file_name().and_then(|n| n.to_str()).unwrap_or("");
                if !name.starts_with("thumbcache_") {
                    continue;
                }
            }
            let size = entry.metadata().map(|m| m.len()).unwrap_or(0);
            match fs::remove_file(&p) {
                Ok(_) => {
                    rep.files_deleted += 1;
                    rep.bytes_freed += size;
                }
                Err(_) => {
                    rep.files_failed += 1;
                    if rep.skipped_locked.len() < 50 {
                        rep.skipped_locked.push(p.to_string_lossy().to_string());
                    }
                }
            }
        }
    }
}

pub fn clean_junk_locations(selected_ids: &[String]) -> CleanReport {
    let defs = get_defined_locations();
    let mut report = CleanReport {
        files_deleted: 0,
        bytes_freed: 0,
        files_failed: 0,
        skipped_locked: Vec::new(),
    };

    for (id, _, _, paths) in defs {
        if !selected_ids.contains(&id) {
            continue;
        }
        let is_thumb = id == "thumbnails";
        for p in paths {
            delete_recursive(&p, is_thumb, &mut report);
        }
    }

    report
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_scan_and_clean_temp_dir() {
        let tmp = tempfile::tempdir().unwrap();
        let f1 = tmp.path().join("junk1.tmp");
        let f2 = tmp.path().join("junk2.log");
        fs::write(&f1, b"hello temp junk").unwrap();
        fs::write(&f2, b"more temp junk").unwrap();

        let (c, b) = walk_dir_stats(tmp.path(), false);
        assert_eq!(c, 2);
        assert_eq!(b, 29);

        let mut rep = CleanReport {
            files_deleted: 0,
            bytes_freed: 0,
            files_failed: 0,
            skipped_locked: Vec::new(),
        };
        delete_recursive(tmp.path(), false, &mut rep);
        assert_eq!(rep.files_deleted, 2);
        assert_eq!(rep.bytes_freed, 29);
        assert!(!f1.exists());
        assert!(!f2.exists());
    }
}
